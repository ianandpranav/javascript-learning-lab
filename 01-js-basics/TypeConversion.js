// String to Number
let age = "22";
let convertedAge = Number(age);

console.log("Age:", convertedAge);
console.log("Type:", typeof convertedAge);

// Number to String
let score = 95;
let convertedScore = String(score);

console.log("Score:", convertedScore);
console.log("Type:", typeof convertedScore);

// Boolean conversion
let value = 1;
let convertedValue = Boolean(value);

console.log("Value:", convertedValue);
console.log("Type:", typeof convertedValue);
