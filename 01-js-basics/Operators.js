let a = 10;
let b = 3;

// Arithmetic
console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Remainder:", a % b);

// Comparison
console.log("a > b:", a > b);
console.log("a < b:", a < b);
console.log("a === b:", a === b);

// Logical
let x = true;
let y = false;

console.log("x && y:", x && y);
console.log("x || y:", x || y);
console.log("!x:", !x);
